import React, { useState } from 'react';
import {
  Copy,
  Check,
  Download,
  Share2,
  Edit3,
  RefreshCw,
  Clock,
  Image as ImageIcon,
  SlidersHorizontal,
  Loader2,
  AlertTriangle,
  BookOpen,
  Sparkles,
} from 'lucide-react';
import type { Story } from '../../types';
import { useReadingPreferences } from '../../hooks/useReadingPreferences';
import { ReadingPreferencesBar } from './ReadingPreferencesBar';

interface StoryReaderProps {
  story: Story;
  isRegenerating?: boolean;
  regenerationError?: string | null;
  onRegenerate: () => Promise<void>;
  onEditPrompt: () => void;
}

export const StoryReader: React.FC<StoryReaderProps> = ({
  story,
  isRegenerating = false,
  regenerationError = null,
  onRegenerate,
  onEditPrompt,
}) => {
  const [copied, setCopied] = useState(false);
  const [shareFeedback, setShareFeedback] = useState<string | null>(null);
  const [showPreferences, setShowPreferences] = useState(false);

  // Reading preferences (persisted to localStorage)
  const {
    preferences,
    setFontFamily,
    setFontSize,
    setLineHeight,
    resetToDefaults,
  } = useReadingPreferences();

  const words = story.content.trim().split(/\s+/).filter(Boolean);
  const wordCount = words.length;
  const readingTimeMinutes = Math.max(1, Math.ceil(wordCount / 200));

  // Break content into clean paragraphs
  const paragraphs = story.content
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter(Boolean);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(`${story.title}\n\n${story.content}`);
      setCopied(true);
      setTimeout(() => setCopied(false), 2200);
    } catch {
      setShareFeedback('Unable to copy story text to clipboard.');
      setTimeout(() => setShareFeedback(null), 3000);
    }
  };

  const handleDownload = () => {
    const slug = story.title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 40);

    const fileBody = `${story.title}
==================================================
StorySpark AI — Where ideas become stories.
Genre: ${story.genre} | Mood: ${story.mood} | Length: ${story.length}
Created: ${new Date(story.created_at).toLocaleString()}
${story.prompt ? `Inspiration Premise: "${story.prompt}"\n` : ''}==================================================

${story.content}

--------------------------------------------------
Generated by StorySpark AI
`;

    const blob = new Blob([fileBody], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${slug || 'story'}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleShare = async () => {
    const shareText = `${story.title}\n\n${story.content}`;

    if (navigator.share) {
      try {
        await navigator.share({
          title: story.title,
          text: shareText,
        });
        return;
      } catch (err) {
        if ((err as Error).name === 'AbortError') return;
      }
    }

    // Fallback: copy full story text and inform the user
    try {
      await navigator.clipboard.writeText(shareText);
      setShareFeedback('Story text copied to your clipboard ready for sharing!');
      setTimeout(() => setShareFeedback(null), 4000);
    } catch {
      setShareFeedback('Unable to copy story text to clipboard.');
      setTimeout(() => setShareFeedback(null), 3000);
    }
  };

  const getFontFamilyClass = () => {
    switch (preferences.fontFamily) {
      case 'serif':
        return 'font-serif';
      case 'mono':
        return 'font-mono';
      default:
        return 'font-sans';
    }
  };

  return (
    <article className="w-full max-w-4xl rounded-3xl border border-[#D5C7B8] bg-[#FFFFFF] shadow-[0_20px_50px_rgba(43,27,42,0.08),0_2px_8px_rgba(43,27,42,0.04)] overflow-hidden transition-all text-left">
      {/* Top subtle decorative accent line */}
      <div className="h-1.5 w-full bg-gradient-to-r from-[#C85E45] via-[#A24867] to-[#8E7C9D]" />

      <div className="p-6 sm:p-9 md:p-10 space-y-7">
        {/* Top Result Banner */}
        <div className="flex flex-wrap items-center justify-between gap-3 pb-3 border-b border-[#F0E8DF]">
          <div className="inline-flex items-center gap-2 rounded-full bg-[#FAF3EE] border border-[#F0D5C9] px-3.5 py-1 text-xs font-semibold text-[#C85E45]">
            <Sparkles className="h-3.5 w-3.5" />
            <span>Generated Story</span>
          </div>
          <div className="flex items-center gap-2 text-xs text-[#7A6C79]">
            <span className="inline-flex items-center gap-1 rounded-md bg-[#EFF6F2] border border-[#D3E8DC] px-2 py-0.5 text-[11px] font-medium text-[#2A6546]">
              <BookOpen className="h-3 w-3" />
              <span>Saved to collection</span>
            </span>
            <span>•</span>
            <span className="font-mono text-[11px]">{new Date(story.created_at).toLocaleDateString()}</span>
          </div>
        </div>

        {/* Regeneration error banner */}
        {regenerationError && (
          <div className="flex items-start gap-2.5 rounded-2xl border border-rose-200 bg-[#FFF5F3] p-4 text-xs text-rose-800 animate-in fade-in">
            <AlertTriangle className="h-4 w-4 shrink-0 text-rose-500 mt-0.5" />
            <div className="flex-1 leading-relaxed">
              <span className="font-semibold">{regenerationError}</span>
              <p className="mt-1 text-[#7A6C79]">Your previous story is still preserved below.</p>
            </div>
          </div>
        )}

        {/* Two Clearly Separated Areas: Story Information Beside Story Actions */}
        <div className="grid grid-cols-1 md:grid-cols-12 gap-6 items-start pb-6 border-b border-[#EFE8DF]">
          {/* Area 1: Story Information */}
          <div className="md:col-span-7 lg:col-span-8 space-y-3.5">
            <h1 className="font-serif text-2xl sm:text-3xl lg:text-4xl font-extrabold tracking-tight text-[#2B1B2A] leading-tight">
              {story.title}
            </h1>

            {/* Story details badges */}
            <div className="flex flex-wrap items-center gap-2">
              <span className="inline-flex items-center rounded-xl bg-[#FAF3EE] border border-[#F0D5C9] px-3 py-1 text-xs font-serif font-semibold text-[#C85E45]">
                {story.genre}
              </span>
              <span className="inline-flex items-center rounded-xl bg-[#F7F2EC] border border-[#EAE2D8] px-3 py-1 text-xs font-serif font-medium text-[#554553]">
                {story.mood}
              </span>
              <span className="inline-flex items-center gap-1.5 rounded-xl bg-[#F7F2EC] border border-[#EAE2D8] px-2.5 py-1 text-xs text-[#6A5868]">
                <Clock className="h-3.5 w-3.5 text-[#9E909D]" />
                <span>{readingTimeMinutes} min read</span>
              </span>
              <span className="inline-flex items-center text-xs text-[#7A6C79] font-mono px-1">
                {wordCount} words
              </span>
              {story.image_filename && (
                <span className="inline-flex items-center gap-1 rounded-xl bg-[#EFF6F2] border border-[#D3E8DC] px-2.5 py-0.5 text-xs text-[#2A6546] font-medium">
                  <ImageIcon className="h-3.5 w-3.5" />
                  <span>Visual Inspiration</span>
                </span>
              )}
            </div>

            {/* Inspiration premise preview */}
            {story.prompt && (
              <div className="rounded-xl border-l-4 border-[#C85E45] bg-[#FAF7F2] p-3 text-xs text-[#554553] leading-relaxed">
                <span className="font-serif font-semibold text-[#2B1B2A]">Inspiration: </span>
                <span className="italic font-serif">"{story.prompt}"</span>
              </div>
            )}
          </div>

          {/* Area 2: Story Actions (Side Panel Beside Story Information) */}
          <div className="md:col-span-5 lg:col-span-4 rounded-2xl border border-[#E6DFD6] bg-[#FAF7F3] p-3.5 flex flex-col gap-2 shrink-0 shadow-2xs">
            <span className="text-[11px] font-bold uppercase tracking-wider text-[#7D6B8D] px-1">
              Story Actions
            </span>

            {/* Primary actions */}
            <div className="flex flex-col gap-1.5">
              <button
                type="button"
                onClick={onRegenerate}
                disabled={isRegenerating}
                className="w-full inline-flex items-center justify-center gap-2 rounded-xl bg-gradient-to-r from-[#C85E45] to-[#A24867] hover:from-[#B8523A] hover:to-[#913B57] px-3.5 py-2 text-xs font-semibold text-white shadow-xs transition-all cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed"
                title="Generate another variation"
              >
                {isRegenerating ? (
                  <>
                    <Loader2 className="h-3.5 w-3.5 animate-spin text-white" />
                    <span>Gathering ideas...</span>
                  </>
                ) : (
                  <>
                    <RefreshCw className="h-3.5 w-3.5 text-white" />
                    <span>Generate Another</span>
                  </>
                )}
              </button>

              <button
                type="button"
                onClick={onEditPrompt}
                disabled={isRegenerating}
                className="w-full inline-flex items-center justify-center gap-2 rounded-xl border border-[#E0D6CB] bg-[#FFFFFF] px-3.5 py-2 text-xs font-medium text-[#4B3949] hover:bg-[#F5EFEB] hover:text-[#2B1B2A] transition-colors cursor-pointer disabled:opacity-50"
                title="Edit prompt and preferences"
              >
                <Edit3 className="h-3.5 w-3.5 text-[#C85E45]" />
                <span>Edit Prompt</span>
              </button>
            </div>

            {/* Utility actions: Share, Appearance, Copy, Download */}
            <div className="grid grid-cols-2 gap-1.5 pt-1.5 border-t border-[#EAE2D8]">
              <button
                type="button"
                onClick={handleShare}
                className="inline-flex items-center justify-center gap-1.5 rounded-xl border border-[#E0D6CB] bg-[#FFFFFF] px-2.5 py-1.5 text-xs font-medium text-[#554553] hover:bg-[#F5EFEB] hover:text-[#2B1B2A] transition-colors cursor-pointer"
                title="Share story text"
              >
                <Share2 className="h-3.5 w-3.5 text-[#7A6C79]" />
                <span>Share</span>
              </button>

              <button
                type="button"
                onClick={() => setShowPreferences((prev) => !prev)}
                className={`inline-flex items-center justify-center gap-1.5 rounded-xl border px-2.5 py-1.5 text-xs font-medium transition-colors cursor-pointer ${
                  showPreferences
                    ? 'border-[#C85E45] bg-[#FAF3EE] text-[#C85E45]'
                    : 'border-[#E0D6CB] bg-[#FFFFFF] text-[#554553] hover:bg-[#F5EFEB] hover:text-[#2B1B2A]'
                }`}
                title="Adjust reading appearance"
              >
                <SlidersHorizontal className="h-3.5 w-3.5 text-[#C85E45]" />
                <span>Appearance</span>
              </button>

              <button
                type="button"
                onClick={handleCopy}
                className="inline-flex items-center justify-center gap-1.5 rounded-xl border border-[#E0D6CB] bg-[#FFFFFF] px-2.5 py-1.5 text-xs font-medium text-[#554553] hover:bg-[#F5EFEB] hover:text-[#2B1B2A] transition-colors cursor-pointer"
                title="Copy story text to clipboard"
              >
                {copied ? (
                  <>
                    <Check className="h-3.5 w-3.5 text-emerald-600" />
                    <span className="text-emerald-700 font-semibold">Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="h-3.5 w-3.5 text-[#7A6C79]" />
                    <span>Copy</span>
                  </>
                )}
              </button>

              <button
                type="button"
                onClick={handleDownload}
                className="inline-flex items-center justify-center gap-1.5 rounded-xl border border-[#E0D6CB] bg-[#FFFFFF] px-2.5 py-1.5 text-xs font-medium text-[#554553] hover:bg-[#F5EFEB] hover:text-[#2B1B2A] transition-colors cursor-pointer"
                title="Download story as .txt"
              >
                <Download className="h-3.5 w-3.5 text-[#7A6C79]" />
                <span>Download</span>
              </button>
            </div>
          </div>
        </div>

        {/* Reading Preferences Drawer */}
        {showPreferences && (
          <ReadingPreferencesBar
            preferences={preferences}
            onSetFontFamily={setFontFamily}
            onSetFontSize={setFontSize}
            onSetLineHeight={setLineHeight}
            onReset={resetToDefaults}
          />
        )}

        {/* Toast Notification */}
        {shareFeedback && (
          <div className="rounded-2xl border border-[#E6DFD6] bg-[#FAF5EE] p-3 text-xs text-[#554553] animate-in fade-in">
            {shareFeedback}
          </div>
        )}

        {/* Story Content Canvas (Main Focus) */}
        <div className="pt-2">
          <div
            className={`space-y-6 text-[#2D1B2A] ${getFontFamilyClass()} transition-all`}
            style={{
              fontSize: `${preferences.fontSize}px`,
              lineHeight: preferences.lineHeight,
            }}
          >
            {paragraphs.map((paragraph, index) => (
              <p key={index} className="leading-relaxed">
                {paragraph}
              </p>
            ))}
          </div>

          {/* Gentle End of Story Signoff */}
          <div className="pt-10 pb-2 text-center">
            <span className="text-xs text-[#A898A7] tracking-widest uppercase">✦ &nbsp; ✦ &nbsp; ✦</span>
          </div>
        </div>
      </div>
    </article>
  );
};
